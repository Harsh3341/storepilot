"""Small psycopg adapter for StorePilot's existing SQLite-shaped SQL interface."""

from contextlib import contextmanager
import re
import sqlite3
from threading import RLock

import psycopg
from psycopg.pq import TransactionStatus


# All StorePilot writers, including separate web processes, use this database lock.
WRITE_LOCK = 748936120421


class Row(tuple):
    """Support both SQLite row indexing and dict(row) for portable backups."""

    def __new__(cls, names, values):
        row = super().__new__(cls, values)
        row._names = names
        row._indexes = {name: index for index, name in enumerate(names)}
        return row

    def __getitem__(self, key):
        return super().__getitem__(self._indexes[key] if isinstance(key, str) else key)

    def keys(self):
        return self._names


def _row_factory(cursor):
    names = tuple(column.name for column in cursor.description or ())
    return lambda values: Row(names, values)


def _parameters(statement: str, has_parameters: bool) -> str:
    """Translate bind markers while preserving quoted SQL text and identifiers."""
    output, quote = [], None
    index = 0
    while index < len(statement):
        character = statement[index]
        if character == "%" and has_parameters:
            output.append("%%")
        elif character == "?" and quote is None:
            output.append("%s")
        else:
            output.append(character)
        if character in ("'", '"'):
            if quote is None:
                quote = character
            elif character == quote:
                if index + 1 < len(statement) and statement[index + 1] == quote:
                    output.append(quote)
                    index += 1
                else:
                    quote = None
        index += 1
    return "".join(output)


def _statements(script: str):
    """Convert the application's trusted schema constants, not user-supplied SQL."""
    statements = [part.strip() for part in script.split(";") if part.strip()]
    # PostgreSQL requires the referenced sales table to exist before orders.
    orders = next((part for part in statements if re.match(
        r"CREATE TABLE IF NOT EXISTS orders\b", part, re.IGNORECASE)), None)
    sales = next((part for part in statements if re.match(
        r"CREATE TABLE IF NOT EXISTS sales\b", part, re.IGNORECASE)), None)
    if orders and sales and statements.index(orders) < statements.index(sales):
        statements.remove(orders)
        statements.insert(statements.index(sales) + 1, orders)
    for statement in statements:
        statement = re.sub(r"\b(\w+)\s+INTEGER\s+PRIMARY KEY\b",
                           r"\1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                           statement, flags=re.IGNORECASE)
        statement = re.sub(r"\bINTEGER\b", "BIGINT", statement, flags=re.IGNORECASE)
        if re.match(r"CREATE TABLE IF NOT EXISTS products\b", statement, re.IGNORECASE):
            # SQLite exposes an implicit rowid; preserve its insertion-order behavior.
            position = statement.rfind(")")
            statement = (statement[:position] + ", rowid BIGINT GENERATED BY DEFAULT AS IDENTITY"
                         + statement[position:])
        yield statement


def _mapped(error):
    if isinstance(error, psycopg.IntegrityError):
        return sqlite3.IntegrityError(str(error))
    return sqlite3.DatabaseError(str(error))


class Cursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    @property
    def description(self):
        return self._cursor.description

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)


class Connection:
    def __init__(self, connection):
        self._connection = connection
        self._identities = {}

    def execute(self, statement: str, parameters=None):
        translated = _parameters(statement, parameters is not None)
        insert = re.match(r"\s*INSERT\s+INTO\s+(\w+)\b", statement, re.IGNORECASE)
        identity = self._identities.get(insert.group(1).lower()) if insert else None
        returning = identity is not None and not re.search(r"\bRETURNING\b", statement, re.IGNORECASE)
        if returning:
            translated = translated.rstrip().rstrip(";") + " RETURNING " + identity
        try:
            cursor = self._connection.execute(translated, parameters)
            lastrowid = cursor.fetchone()[0] if returning and cursor.rowcount else None
            return Cursor(cursor, lastrowid)
        except psycopg.Error as error:
            raise _mapped(error) from error

    def executemany(self, statement: str, parameters):
        try:
            cursor = self._connection.cursor()
            cursor.executemany(_parameters(statement, True), parameters)
            return Cursor(cursor)
        except psycopg.Error as error:
            raise _mapped(error) from error

    def executescript(self, script: str):
        # Auth initializes its schema outside Database.transaction(). Keep that
        # initialization atomic and coordinate concurrent web-process startups.
        if self._connection.info.transaction_status == TransactionStatus.IDLE:
            try:
                with self._connection.transaction():
                    self.execute("SELECT pg_advisory_xact_lock(?)", (WRITE_LOCK,))
                    self.executescript(script)
            except psycopg.Error as error:
                raise _mapped(error) from error
            return
        for statement in _statements(script):
            table = re.match(r"CREATE TABLE(?: IF NOT EXISTS)?\s+(\w+)\b", statement, re.IGNORECASE)
            identity = re.search(r"\b(\w+)\s+BIGINT\s+GENERATED BY DEFAULT AS IDENTITY\b",
                                 statement, re.IGNORECASE)
            if table and identity:
                self._identities[table.group(1).lower()] = identity.group(1)
            self.execute(statement)

    def commit(self):
        try:
            self._connection.commit()
        except psycopg.Error as error:
            raise _mapped(error) from error

    def rollback(self):
        try:
            self._connection.rollback()
        except psycopg.Error as error:
            raise _mapped(error) from error

    def close(self):
        self._connection.close()


class PostgresDatabase:
    def __init__(self, url: str, schema: str):
        self.lock = RLock()
        try:
            raw = psycopg.connect(url, autocommit=True, row_factory=_row_factory, connect_timeout=10)
        except psycopg.Error as error:
            raise _mapped(error) from error
        self.connection = Connection(raw)
        try:
            with self.transaction():
                self.connection.executescript(schema)
        except BaseException:
            self.connection.close()
            raise

    @contextmanager
    def transaction(self):
        with self.lock:
            self.connection.execute("BEGIN")
            try:
                self.connection.execute("SELECT pg_advisory_xact_lock(?)", (WRITE_LOCK,))
                yield self.connection
                self.connection.commit()
            except BaseException:
                self.connection.rollback()
                raise

    def close(self):
        with self.lock:
            self.connection.close()
